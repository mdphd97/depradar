"""AI Agent Integration Utilities for DepRadar.
Provides prompt-ready Markdown contexts, dependency queries, and CLI helpers.
"""

import platform
from typing import List, Dict, Any
from .models import GraphData, Node

def generate_agent_context(graph: GraphData) -> str:
    """Generates a compact, high-value Markdown briefing for an AI agent's system prompt or context window."""
    os_name = platform.system()
    nodes = graph.nodes
    runtimes = [n for n in nodes if n.type == "runtime"]
    venvs = [n for n in nodes if n.type == "python-venv"]
    projects = [n for n in nodes if n.type == "project"]
    heavy = sorted(nodes, key=lambda x: x.size_bytes, reverse=True)[:5]
    stale = [n for n in nodes if n.status == "stale"]

    lines = [
        "# System & Environment Context (Generated by DepRadar)",
        f"**Host OS**: {os_name} {platform.release()} ({platform.machine()})",
        f"**Total Tracked Components**: {len(nodes)} nodes | {len(graph.links)} dependency connections",
        "",
        "## Active Host Runtimes & Interpreters",
    ]
    for r in runtimes:
        lines.append(f"- **{r.name}** (`{r.path}`): {r.notes}")

    lines.append("\n## Detected Developer Workspaces & Projects")
    for p in projects:
        lines.append(f"- **{p.name}** (`{p.path}`): [{p.category}] {p.notes}")

    lines.append("\n## Python Virtual Environments")
    for v in venvs:
        pkg_cnt = len(v.installed_packages) if v.installed_packages else "Unknown"
        lines.append(f"- **{v.name}** (`{v.path}`): {v.size_human} | {pkg_cnt} installed packages | Status: `{v.status}`")

    lines.append("\n## Top Disk Consumers")
    for h in heavy:
        lines.append(f"- **{h.name}**: {h.size_human} (`{h.path}`)")

    if stale:
        lines.append("\n## Stale / Cleanup Candidates")
        for s in stale:
            cmd = s.uninstall_cmd or f"rm -rf '{s.path}'"
            lines.append(f"- **{s.name}** ({s.size_human}, {s.days_inactive}d inactive) -> Cleanup: `{cmd}`")

    lines.append("\n*To query individual package details, run: `depradar query <package_name> --json`*")
    return "\n".join(lines)

def query_dependencies(graph: GraphData, term: str) -> List[Dict[str, Any]]:
    """Searches graph for matching nodes and returns connectivity context."""
    q = term.lower().strip()
    results = []
    for n in graph.nodes:
        name_match = q in n.name.lower() or q in n.id.lower() or q in n.notes.lower()
        pkg_match = any(q in p.get("name", "").lower() for p in n.installed_packages) if n.installed_packages else False
        if name_match or pkg_match:
            # Upstream & Downstream
            up = [
                {"source": (l.source if isinstance(l.source, str) else l.source.id), "rel": l.relationship, "desc": l.description}
                for l in graph.links if (l.target == n.id or (isinstance(l.target, dict) and l.target.get("id") == n.id))
            ]
            down = [
                {"target": (l.target if isinstance(l.target, str) else l.target.id), "rel": l.relationship, "desc": l.description}
                for l in graph.links if (l.source == n.id or (isinstance(l.source, dict) and l.source.get("id") == n.id))
            ]
            results.append({
                "name": n.name,
                "id": n.id,
                "category": n.category,
                "type": n.type,
                "status": n.status,
                "size": n.size_human,
                "path": n.path,
                "notes": n.notes,
                "required_by": up,
                "requires": down,
                "installed_packages": n.installed_packages[:15] if n.installed_packages else []
            })
    return results

def get_stale_items(graph: GraphData) -> List[Dict[str, Any]]:
    """Returns all stale/orphan items and cleanup commands."""
    return [
        {
            "name": n.name,
            "category": n.category,
            "type": n.type,
            "size": n.size_human,
            "path": n.path,
            "days_inactive": n.days_inactive,
            "cleanup_cmd": n.uninstall_cmd or f"rm -rf '{n.path}'"
        }
        for n in graph.nodes if n.status == "stale"
    ]
